// The project map over the API, as the desktop app's Map view uses it: the map of a root's code
// checkout, one node with its neighbours, search by words or file, the check, the index and init.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { initRoot } from '@swarmup/core';
import { startApi, Supervisor } from '../src/index.js';

const dirs: string[] = [];
const sups: Supervisor[] = [];

// As in attachments-api.test.ts: take this test's supervisors and folders before awaiting.
afterEach(async () => {
  const mine = sups.splice(0);
  const gone = dirs.splice(0);
  try {
    for (const s of mine) {
      s.stop({ killRuns: true });
      await s.close();
    }
  } finally {
    for (const d of gone) rmSync(d, { recursive: true, force: true, maxRetries: 5 });
  }
}, 90_000);

function temp(): string {
  const d = mkdtempSync(join(tmpdir(), 'swarmupd-map-'));
  dirs.push(d);
  return d;
}

const git = (cwd: string, ...args: string[]): string =>
  execFileSync('git', ['-c', 'user.name=T', '-c', 'user.email=t@example.com', ...args], {
    cwd,
    encoding: 'utf8',
    windowsHide: true,
  });

function write(top: string, rel: string, text: string): void {
  const file = join(top, ...rel.split('/'));
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
}

const INDEX = [
  '# Project map index',
  '',
  '<!-- Generated by `swarmup map index`; do not edit. Run it again after you change a node. -->',
  '',
  '- `index` — root — A demo shop',
  '- `core` — module — The cart and prices',
  '- `docs` — area — User guides',
  '',
].join('\n');

/** A repo with a data root; `withMap` adds a committed map with a root, `core` and `docs`. */
function repo(name: string, prefix: string, withMap: boolean): string {
  const dir = temp();
  git(dir, 'init', '-q', '-b', 'main');
  git(dir, 'config', 'core.autocrlf', 'false');
  initRoot(dir, { name, prefix, human: 'human:dawid' });
  write(dir, 'src/cart.ts', 'export const cart = 1;\n');
  write(dir, 'docs/guide.md', '# Guide\n');
  if (withMap) {
    write(
      dir,
      '.swarmup/map/index.md',
      '---\nkind: root\ntype: code\nsummary: A demo shop\nlinks: [core, docs]\n---\n\n# Shop\n',
    );
    write(
      dir,
      '.swarmup/map/core.md',
      '---\nkind: module\nsummary: The cart and prices\ncovers: [src/cart.ts]\nlinks: [docs, gone]\nverified: abc123\n---\n\n# Core\n\nThe **cart** sums prices.\n',
    );
    write(
      dir,
      '.swarmup/map/docs.md',
      '---\nkind: area\nsummary: User guides\ncovers: [docs, https://example.com/help]\nreview_after: 2020-01-01\n---\n\n# Docs\n',
    );
    write(dir, '.swarmup/map/_INDEX.md', INDEX);
  }
  git(dir, 'add', '-A');
  git(dir, 'commit', '-q', '-m', 'start');
  return dir;
}

async function setup() {
  const shop = repo('shop', 'SHOP', true);
  const web = repo('web', 'WEB', false);
  const config = join(temp(), 'config.yml');
  writeFileSync(config, 'me: human:dawid\nopsd:\n  sync: false\n');
  const env = {
    ...process.env,
    SWARMUP_CONFIG: config,
    SWARMUP_STATE_DIR: temp(),
  } as NodeJS.ProcessEnv;
  delete env.SWARMUP_AGENT;
  delete env.SWARMUP_ROOTS;
  const sup = new Supervisor({
    env,
    cwd: shop,
    user: { me: 'human:dawid', roots: [web] },
    freeMem: () => 64 * 2 ** 30,
  });
  sups.push(sup);
  const api = await startApi(sup, { port: 0, token: 'map-token', version: 't', build: '1' });
  const call = async (method: 'GET' | 'POST', path: string, body?: unknown) => {
    const res = await fetch(`http://127.0.0.1:${api.port}${path}`, {
      method,
      headers: { authorization: 'Bearer map-token', 'content-type': 'application/json' },
      body: body === undefined ? undefined : JSON.stringify(body),
    });
    return { status: res.status, data: (await res.json()) as Record<string, unknown> };
  };
  return { shop, web, call };
}

type Brief = { id: string; links: string[]; broken: string[]; score?: number };

describe('GET /api/map', () => {
  it('lists the nodes of the root code checkout with resolved links', async () => {
    const { shop, call } = await setup();
    const res = await call('GET', '/api/map?root=shop');
    expect(res.status).toBe(200);
    expect(res.data).toMatchObject({
      root: 'shop',
      exists: true,
      type: 'code',
      summary: 'A demo shop',
      dir: join(shop, '.swarmup', 'map'),
    });
    const nodes = res.data.nodes as Array<Brief & Record<string, unknown>>;
    expect(nodes.map((n) => n.id)).toEqual(['index', 'core', 'docs']);
    expect(nodes[1]).toMatchObject({
      file: '.swarmup/map/core.md',
      kind: 'module',
      covers: ['src/cart.ts'],
      links: ['docs'],
      broken: ['gone'],
      verified: 'abc123',
      size: 3,
    });
    expect(nodes[2]).toMatchObject({ review_after: '2020-01-01' });
    // The default root is the same project.
    expect(((await call('GET', '/api/map')).data.nodes as unknown[]).length).toBe(3);
  });

  it('says where a map would go and which type init would pick when there is none', async () => {
    const { web, call } = await setup();
    const res = await call('GET', '/api/map?root=web');
    expect(res.data).toMatchObject({ root: 'web', exists: false, dir: null, detected: 'code' });
    expect(String(res.data.top).toLowerCase()).toBe(web.toLowerCase());
    expect((await call('GET', '/api/map?root=nope')).status).toBe(400);
  });
});

describe('GET /api/map/node and /api/map/search', () => {
  it('reads one node with its body and neighbours', async () => {
    const { call } = await setup();
    const res = await call('GET', '/api/map/node?root=shop&id=core');
    expect(res.status).toBe(200);
    expect(res.data.body).toContain('The **cart** sums prices.');
    expect((res.data.linksTo as Brief[]).map((n) => n.id)).toEqual(['docs']);
    expect((res.data.linkedFrom as Brief[]).map((n) => n.id)).toEqual(['index']);
    expect((await call('GET', '/api/map/node?root=shop&id=nope')).status).toBe(404);
    expect((await call('GET', '/api/map/node?root=shop')).status).toBe(400);
  });

  it('finds nodes by words, best first, and by the file they cover', async () => {
    const { shop, call } = await setup();
    const words = (await call('GET', '/api/map/search?root=shop&q=cart'))
      .data as unknown as Brief[];
    expect(words.map((n) => n.id)).toEqual(['core']);
    expect(words[0]!.score).toBeGreaterThan(0);
    const file = (await call('GET', '/api/map/search?root=shop&file=docs%2Fguide.md'))
      .data as unknown as Brief[];
    expect(file.map((n) => n.id)).toEqual(['docs']);
    const abs = encodeURIComponent(join(shop, 'src', 'cart.ts'));
    const byAbs = (await call('GET', `/api/map/search?root=shop&file=${abs}`))
      .data as unknown as Brief[];
    expect(byAbs.map((n) => n.id)).toEqual(['core']);
    // A project without a map has nothing to search.
    expect((await call('GET', '/api/map/search?root=web&q=x')).status).toBe(409);
  });
});

describe('POST /api/map/check and /api/map/index', () => {
  it('reports errors and warnings against the base, with the node or path', async () => {
    const { shop, call } = await setup();
    git(shop, 'checkout', '-q', '-b', 'work');
    write(shop, 'src/cart.ts', 'export const cart = 2;\n');
    write(shop, 'src/tax.ts', 'export const tax = 1;\n');
    const res = await call('POST', '/api/map/check', { root: 'shop', base: 'main' });
    expect(res.status).toBe(200);
    expect(res.data).toMatchObject({ hasMap: true, ok: false, nodes: 3, changed: 2 });
    expect((res.data.base as { ref: string }).ref).toBe('main');
    const errors = res.data.errors as Array<{ code: string; node?: string; path?: string }>;
    expect(errors.map((e) => [e.code, e.node ?? e.path])).toEqual([
      ['missing-link', 'core'],
      ['uncovered', 'src/tax.ts'],
    ]);
    const warnings = res.data.warnings as Array<{ code: string; node?: string }>;
    expect(warnings.map((w) => [w.code, w.node]).sort()).toEqual([
      ['node-not-updated', 'core'],
      ['review-due', 'docs'],
    ]);
    const bad = await call('POST', '/api/map/check', { root: 'shop', base: 'no-such-branch' });
    expect(bad.status).toBe(400);
    expect(String(bad.data.error)).toContain('no merge base');
  });

  it('rebuilds a stale _INDEX.md', async () => {
    const { shop, call } = await setup();
    const file = join(shop, '.swarmup', 'map', '_INDEX.md');
    writeFileSync(file, '# stale\n');
    const before = await call('POST', '/api/map/check', { root: 'shop' });
    expect((before.data.errors as Array<{ code: string }>).map((e) => e.code)).toContain(
      'stale-index',
    );
    const res = await call('POST', '/api/map/index', { root: 'shop' });
    expect(res).toMatchObject({ status: 200, data: { nodes: 3 } });
    expect(readFileSync(file, 'utf8')).toBe(INDEX);
    expect((await call('POST', '/api/map/index', { root: 'web' })).status).toBe(409);
  });
});

describe('POST /api/map/init', () => {
  it('starts a map of the detected type, or the one asked for, once', async () => {
    const { web, call } = await setup();
    const res = await call('POST', '/api/map/init', { root: 'web' });
    expect(res.status).toBe(201);
    expect(res.data).toMatchObject({ type: 'code', detected: true });
    expect(existsSync(join(web, '.swarmup', 'map', 'index.md'))).toBe(true);
    const map = await call('GET', '/api/map?root=web');
    expect(map.data).toMatchObject({ exists: true, type: 'code' });
    expect((await call('POST', '/api/map/init', { root: 'web' })).status).toBe(409);
    expect((await call('POST', '/api/map/init', { root: 'web', type: 'poster' })).status).toBe(400);
  });

  it('takes the type the person picked', async () => {
    const { web, call } = await setup();
    rmSync(join(web, 'src'), { recursive: true });
    const res = await call('POST', '/api/map/init', { root: 'web', type: 'website' });
    expect(res.data).toMatchObject({ type: 'website', detected: false });
    expect(readFileSync(join(web, '.swarmup', 'map', 'index.md'), 'utf8')).toContain(
      'type: website',
    );
  });
});
